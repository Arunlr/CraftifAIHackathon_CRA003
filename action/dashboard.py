def main():
    ap = argparse.ArgumentParser(description="PipeGen Action Engine next-gen dashboard")
    ap.add_argument("--state-dir", default="run")
    ap.add_argument("--host", default="0.0.0.0")
    ap.add_argument("--port", type=int, default=8050)
    args = ap.parse_args()
    state_file = os.path.join(args.state_dir, "state.json")
    base_dir = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    media_dir = os.path.join(base_dir, "media")
    page = HTML.encode("utf-8")

    class Handler(http.server.BaseHTTPRequestHandler):
        def _send(self, code, body, ctype, extra_headers=None):
            self.send_response(code)
            self.send_header("Content-Type", ctype)
            self.send_header("Cache-Control", "no-store")
            if extra_headers:
                for k, v in extra_headers.items():
                    self.send_header(k, v)
            self.send_header("Content-Length", str(len(body)))
            self.end_headers()
            self.wfile.write(body)

        def do_GET(self):  # noqa: N802
            url_path = urllib.parse.urlparse(self.path).path

            if url_path in ("/api/state", "api/state"):
                try:
                    with open(state_file, "rb") as f:
                        body = f.read()
                except OSError:
                    body = b'{"waiting": true}'
                self._send(200, body, "application/json")

            elif url_path.startswith("/media/"):
                rel_path = url_path[len("/media/"):]
                safe_path = os.path.normpath(os.path.join(media_dir, rel_path))
                if not safe_path.startswith(media_dir) or not os.path.exists(safe_path):
                    self._send(404, b"media not found", "text/plain")
                    return

                mime, _ = mimetypes.guess_type(safe_path)
                mime = mime or "application/octet-stream"
                file_size = os.path.getsize(safe_path)

                range_header = self.headers.get("Range")
                if range_header and range_header.startswith("bytes="):
                    try:
                        ranges = range_header[6:].split("-")
                        start = int(ranges[0]) if ranges[0] else 0
                        end = int(ranges[1]) if ranges[1] else file_size - 1
                        end = min(end, file_size - 1)
                        length = end - start + 1

                        with open(safe_path, "rb") as f:
                            f.seek(start)
                            data = f.read(length)

                        self.send_response(206)
                        self.send_header("Content-Type", mime)
                        self.send_header("Content-Range", f"bytes {start}-{end}/{file_size}")
                        self.send_header("Content-Length", str(length))
                        self.send_header("Accept-Ranges", "bytes")
                        self.end_headers()
                        self.wfile.write(data)
                        return
                    except Exception:
                        pass

                try:
                    with open(safe_path, "rb") as f:
                        data = f.read()
                    self._send(200, data, mime, {"Accept-Ranges": "bytes"})
                except OSError:
                    self._send(500, b"error reading file", "text/plain")

            elif url_path in ("/", "/index.html"):
                self._send(200, page, "text/html; charset=utf-8")
            else:
                self._send(404, b"not found", "text/plain")

        def log_message(self, *a):
            pass

    srv = http.server.ThreadingHTTPServer((args.host, args.port), Handler)
    print(f"\n==================================================================")
    print(f"  GAJA-RAKSHAK MISSION CONTROL DASHBOARD ONLINE")
    print(f"  URL: http://localhost:{args.port}  (reading {state_file})")
    print(f"==================================================================\n", flush=True)

    try:
        srv.serve_forever()
    except KeyboardInterrupt:
        pass


if __name__ == "__main__":
    main()
